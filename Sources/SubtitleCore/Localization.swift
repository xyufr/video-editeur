import Foundation

/// Application UI language is independent of subtitle languages and the system locale.
public enum InterfaceLanguage: String, CaseIterable { case zh, en
    public static let preferenceKey="editor.interfaceLanguage"
    public static var preferred: InterfaceLanguage { InterfaceLanguage(rawValue:UserDefaults.standard.string(forKey:preferenceKey) ?? "") ?? .zh }
    public static let current=preferred
}
public func L(_ key: String, _ arguments: [String] = []) -> String {
    return UILocalization.text(key,arguments:arguments,language:InterfaceLanguage.current)
}
public enum UILocalization {
    public static func text(_ key: String, arguments: [String] = [], language: InterfaceLanguage) -> String {
        let template=language == .en ? (english[key] ?? key) : key
        // Match only the template, never tokens that happen to occur in user data.
        let pattern=try! NSRegularExpression(pattern:"\\{([0-9]+)\\}")
        let ns=template as NSString
        var output=template
        for match in pattern.matches(in:template,range:NSRange(location:0,length:ns.length)).reversed() {
            if let index=Int(ns.substring(with:match.range(at:1))),arguments.indices.contains(index),let range=Range(match.range,in:output) {
                output.replaceSubrange(range,with:arguments[index])
            }
        }
        return output
    }
